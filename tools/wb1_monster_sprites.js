// Make editor/js/wb1monsters.js, the T Rex and scorpion artwork the "T Rex and scorpion" patch adds to
// World Builder 2 (which has their scripts and stats but only their frozen sprites):
//   node wb1_monster_sprites.js "World Builder/worldbuilder/worldbuilder.dcr"
// WB1's sprites (16-bit T Rex, 8-bit scorpion with its own palette) are converted to 32-bit the
// way WB2 stores its map sprites: white with alpha 0 where they're see-through.
const fs = require("fs");
const path = require("path");
const WB = require("../js/wbcore.js");

const MONSTERS = ["trex", "scorpion"];

(async () => {
  const src = process.argv[2];
  if (!src) { console.error("usage: node wb1_monster_sprites.js <World Builder 1 .dcr or Launcher.exe>"); process.exit(1); }
  const mv = await WB.openMovie(fs.readFileSync(src));
  const game = await mv.loadGame();
  if (game.edition !== 1) throw new Error(`${src} isn't World Builder 1`);
  const out = {};
  const names = mv.members.filter((m) => m.type === 1 && m.name && new RegExp(`^monster\\.(${MONSTERS.join("|")})\\.`).test(m.name))
    .map((m) => m.name).sort();
  let bytes = 0;
  for (const name of names) {
    const img = await mv.bitmap(name);
    if (!img) throw new Error(`can't decode ${name}`);
    const bitd = WB.bitd32(img, true);
    bytes += bitd.length;
    out[name] = [img.w, img.h, img.regX, img.regY, Buffer.from(bitd).toString("base64")];
  }
  for (const n of MONSTERS) {
    for (const d of ["up", "down", "left", "right"]) {
      if (!names.some((x) => x === `monster.${n}.${d}` || x.startsWith(`monster.${n}.${d}.`))) throw new Error(`${n} has no ${d} sprite`);
    }
  }
  const js = `/* Generated by wb1_monster_sprites.js from World Builder 1: its T Rex and scorpion sprites as
 * 32-bit BITD data, for the editor's "T Rex and scorpion" patch to World Builder 2.
 * name: [width, height, regX, regY, base64 BITD] */
(function (root) {
  const SPRITES = {
${Object.entries(out).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}
  };
  if (typeof module !== "undefined" && module.exports) module.exports = SPRITES;
  else root.WB1_MONSTER_SPRITES = SPRITES;
})(typeof self !== "undefined" ? self : this);
`;
  const dest = path.join(__dirname, "..", "js", "wb1monsters.js");
  fs.writeFileSync(dest, js);
  console.log(`${names.length} sprites (${bytes} bytes of bitmap data) -> ${dest}`);
})().catch((e) => { console.error(e.message); process.exit(1); });
